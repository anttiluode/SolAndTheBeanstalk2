"use strict";
const assert=require("node:assert/strict"),{chromium}=require("playwright-core"),fs=require("node:fs"),path=require("node:path");
(async()=>{
 const exe=["/usr/bin/google-chrome","/usr/bin/google-chrome-stable","/usr/bin/chromium","/usr/bin/chromium-browser"].find(fs.existsSync);
 if(!exe)throw Error("A Chromium executable is needed for the browser test.");
 const browser=await chromium.launch({headless:true,executablePath:exe,args:["--no-sandbox","--enable-webgl","--use-gl=angle","--use-angle=swiftshader","--enable-unsafe-swiftshader"]});
 const page=await browser.newPage({viewport:{width:960,height:600},deviceScaleFactor:1});
 const errors=[];page.on("pageerror",e=>errors.push(e.message));page.on("console",m=>{if(m.type()==="error")errors.push(m.text())});
 await page.goto("file://"+path.join(__dirname,"..","index.html")+"?ci=1&quality=low#seed=152734",{waitUntil:"domcontentloaded"});
 await page.locator("#begin:enabled").waitFor({timeout:100000});
 const initial=await page.evaluate(()=>({ready:SkyEngine.ready,webgl:!!document.getElementById("gl").getContext("webgl2"),shaderError:document.getElementById("boot").classList.contains("err")}));
 assert.deepEqual(initial,{ready:true,webgl:true,shaderError:false});
 await page.screenshot({path:"beanstalk2-title.png"});
 await page.locator("#begin").click();
 await page.locator("#fire").click();
 assert.equal(await page.evaluate(()=>SkyEngine.state.shots[0]),1);
 assert.equal(await page.evaluate(()=>SkyCore.ready(SkyEngine.state)),true);
 await page.screenshot({path:"beanstalk2-first-vine.png"});
 // The camera flies through the existing PsychedelicGarden corridor, instead of teleporting the shader.
 await page.locator("#follow").click();
 await page.waitForFunction(()=>SkyEngine.room===1,{timeout:15000});
 await page.locator("#fire").click();
 assert.ok(await page.evaluate(()=>SkyEngine.state.pressure)>.60);
 assert.match(await page.locator("#pin-message").text(),/SAGGING/);
 await page.screenshot({path:"beanstalk2-strained-pin.png"});
 await page.locator("#root").click();
 assert.equal(await page.evaluate(()=>SkyEngine.state.rooted[1]),true);
 await page.waitForTimeout(240);
 await page.locator("#fire").click();
 assert.equal(await page.evaluate(()=>SkyCore.ready(SkyEngine.state)),true);
 await page.locator("#follow").click();
 await page.waitForFunction(()=>SkyEngine.room===2,{timeout:15000});
 await page.locator("#fire").click();
 await page.locator("#root").click();
 await page.waitForTimeout(240);
 await page.locator("#fire").click();
 await page.locator("#follow").click();
 await page.waitForFunction(()=>SkyEngine.room===3,{timeout:15000});
 await page.locator("#fire").click();
 await page.locator("#root").click();
 await page.waitForTimeout(240);
 await page.locator("#fire").click();
 await page.waitForTimeout(240);
 await page.locator("#fire").click();
 assert.equal(await page.evaluate(()=>SkyCore.ready(SkyEngine.state)),true);
 await page.screenshot({path:"beanstalk2-keeper.png"});
 await page.locator("#follow").click();
 await page.locator("#ending").waitFor({state:"visible",timeout:5000});
 await page.locator("#choice-hold").click();
 assert.deepEqual(await page.evaluate(()=>[SkyEngine.state.completed,SkyEngine.state.choice]),[true,"hold"]);
 assert.deepEqual(errors,[],errors.join("\n"));
 console.log("PASS WebGL2 CI lightweight shader, four chambers, pin strain UI, rooting, ending, no browser errors. Full raymarch shader is NOT exercised in CI mode.");
 await browser.close();
})().catch(e=>{console.error(e);process.exitCode=1});
